// oxlint-disable effecttsgo/node-builtin-import, effecttsgo/process-env -- evaluated by oxlint while it loads its config, outside any Effect runtime

import { mkdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { dirname, isAbsolute, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import type { AllowWarnDeny, DummyRule, OxlintConfig, OxlintOverride } from "oxlint";

/**
 * `"all"` checks every line. `"changed"` checks only lines changed on the branch (the working tree
 * against the merge base of `HEAD` and the default branch), so findings on untouched lines are
 * ignored: on a deterministic rule this is a ratchet, where new code must pass and old code is left
 * alone.
 */
export type Mode = "all" | "changed";

/** A rule's severity with its mode, and its options when it takes any. */
export interface RuleWithMode {
	readonly level: AllowWarnDeny;
	readonly mode?: Mode;
	readonly options?: ReadonlyArray<unknown>;
}

export type AntiSlopRule = DummyRule | RuleWithMode;

export type AntiSlopRules = Readonly<Record<string, AntiSlopRule>>;

export interface AntiSlopOverride extends Omit<OxlintOverride, "rules"> {
	readonly rules?: AntiSlopRules;
}

export interface AntiSlopConfig extends Omit<OxlintConfig, "rules" | "overrides"> {
	readonly rules?: AntiSlopRules;
	readonly overrides?: ReadonlyArray<AntiSlopOverride>;
}

export interface AntiSlopConfigOptions {
	/** The git ref whose merge base with `HEAD` `"changed"` rules diff against. Defaults to `ANTI_SLOP_BASE`, then the default branch. */
	readonly base?: string;
	/** The directory relative `jsPlugins` specifiers resolve from. Defaults to the calling config file's directory. */
	readonly root?: string;
	/** Defaults to `process.env`. */
	readonly env?: Readonly<Record<string, string | undefined>>;
}

/** What `settings.changedLines` carries to Jev plugins and wrapped plugins (see `oxlint-plugin-jev/changed`). */
export interface ChangedLinesSettings {
	readonly rules: Readonly<Record<string, Mode>>;
	readonly base?: string;
}

export type AntiSlopOxlintConfig = OxlintConfig & {
	readonly settings: NonNullable<OxlintConfig["settings"]> & { readonly changedLines: ChangedLinesSettings };
};

type RuleKind = "native" | "js" | "jev";

const OFF_LEVELS: ReadonlySet<unknown> = new Set(["off", "allow", 0]);

/** Jev plugins are named `jev` or end in `-jev`, like `anti-slop-effect-jev`. */
const isJevPlugin = (name: string): boolean => name === "jev" || name.endsWith("-jev");

const pluginOf = (rule: string): string | undefined => (rule.includes("/") ? rule.slice(0, rule.indexOf("/")) : undefined);

const isRuleWithMode = (entry: AntiSlopRule): entry is RuleWithMode =>
	typeof entry === "object" && !Array.isArray(entry);

const fail = (message: string): never => {
	throw new Error(`anti-slop config: ${message}`);
};

function callerDirectory(): string | undefined {
	const self = import.meta.url.split("?")[0];
	for (const match of (new Error().stack ?? "").matchAll(/(file:\/\/[^\s?)]+)(?:\?[^\s)]*)?:\d+:\d+/g)) {
		const url = match[1];
		if (url !== undefined && url !== self) return dirname(fileURLToPath(url));
	}
	return undefined;
}

/**
 * Oxlint loads a plugin from a module specifier and nothing else, so the wrapped copy of a plugin
 * is a generated module that imports the original and wraps it.
 */
function writeWrapper(root: string, name: string, specifier: string): string {
	const target =
		specifier.startsWith(".") || isAbsolute(specifier) ? pathToFileURL(resolve(root, specifier)).href : specifier;
	const wrap = new URL("./wrap.ts", import.meta.url).href;
	const source = [
		`// Generated by anti-slop's defineAntiSlopConfig for the "${name}" plugin (${specifier}). Do not edit.`,
		`import plugin from ${JSON.stringify(target)};`,
		`import { changedLinesPlugin } from ${JSON.stringify(wrap)};`,
		"",
		"export default changedLinesPlugin(plugin);",
		"",
	].join("\n");
	const directory = join(root, "node_modules", ".cache", "anti-slop", "plugins");
	const file = join(directory, `${name.replace(/[^\w.-]/g, "_")}.mjs`);
	let current: string | undefined;
	try {
		current = readFileSync(file, "utf8");
	} catch {
		current = undefined;
	}
	if (current !== source) {
		mkdirSync(directory, { recursive: true });
		// Concurrent oxlint processes may write the same file; a rename never exposes a partial one.
		const temporary = `${file}.${process.pid}.tmp`;
		writeFileSync(temporary, source);
		renameSync(temporary, file);
	}
	return file;
}

/**
 * Expands anti-slop rule entries into a standard Oxlint config. Each rule entry is a severity, an
 * Oxlint `[severity, ...options]` array, or `{ level, mode, options }`. Deterministic rules default
 * to mode `"all"`, Jev rules (plugins named `jev` or `*-jev`) to `"changed"`.
 *
 * - Per-rule modes go to `settings.changedLines`, which Jev plugins and the wrapped plugins read.
 * - A JS plugin with a rule in `"changed"` mode is registered as a wrapped copy, under the same
 *   name, that drops findings on unchanged lines.
 * - Built-in Oxlint rules and `effecttsgo/*` run natively, so `"changed"` on them is an error.
 * - Jev rules are turned off unless `ANTI_SLOP_JEV=1`, so the editor and plain `oxlint` runs never
 *   make paid requests.
 * - `ANTI_SLOP_MODE=all` checks every line with every rule, for full runs.
 */
export function defineAntiSlopConfig(config: AntiSlopConfig, options: AntiSlopConfigOptions = {}): AntiSlopOxlintConfig {
	const env = options.env ?? process.env;
	const forced = env.ANTI_SLOP_MODE?.trim() ?? "";
	if (forced !== "" && forced !== "all") fail(`ANTI_SLOP_MODE must be "all" or unset, not "${forced}"`);
	const jevOn = ["1", "true"].includes(env.ANTI_SLOP_JEV?.trim().toLowerCase() ?? "");
	const base = options.base ?? (env.ANTI_SLOP_BASE?.trim() || undefined);

	const specifiers = new Map<string, string>();
	for (const entry of config.jsPlugins ?? []) {
		if (typeof entry !== "string") specifiers.set(entry.name, entry.specifier);
	}

	const kindOf = (rule: string): RuleKind => {
		const plugin = pluginOf(rule);
		if (plugin === undefined || !specifiers.has(plugin)) return "native";
		return isJevPlugin(plugin) ? "jev" : "js";
	};

	const explicitModes = new Map<string, Mode>();
	const enabled = new Set<string>();

	const expandRules = (rules: AntiSlopRules | undefined): Record<string, DummyRule> | undefined => {
		if (rules === undefined) return undefined;
		const expanded: Record<string, DummyRule> = {};
		for (const [rule, entry] of Object.entries(rules)) {
			const kind = kindOf(rule);
			if (!isRuleWithMode(entry)) {
				const level = Array.isArray(entry) ? entry[0] : entry;
				expanded[rule] = kind === "jev" && !jevOn && !OFF_LEVELS.has(level) ? "off" : entry;
				if (!OFF_LEVELS.has(level)) enabled.add(rule);
				continue;
			}
			const { level, mode, options: ruleOptions = [] } = entry;
			if (mode === "changed" && kind === "native") {
				fail(
					`"${rule}" cannot use mode "changed": only rules from a JS plugin registered as { name, specifier } in this config's jsPlugins can. Built-in Oxlint rules and effecttsgo/* run natively and always check every line.`,
				);
			}
			if (mode !== undefined) {
				const previous = explicitModes.get(rule);
				if (previous !== undefined && previous !== mode) {
					fail(`"${rule}" is set to mode "${previous}" in one place and "${mode}" in another; a rule has one mode`);
				}
				explicitModes.set(rule, mode);
			}
			const effective = kind === "jev" && !jevOn && !OFF_LEVELS.has(level) ? "off" : level;
			expanded[rule] = ruleOptions.length === 0 ? effective : [effective, ...ruleOptions];
			if (!OFF_LEVELS.has(level)) enabled.add(rule);
		}
		return expanded;
	};

	const rules = expandRules(config.rules);
	const overrides = config.overrides?.map(({ rules: overrideRules, ...override }): OxlintOverride => {
		const expanded = expandRules(overrideRules);
		return expanded === undefined ? override : { ...override, rules: expanded };
	});

	const modes: Record<string, Mode> = {};
	const wrapped = new Set<string>();
	for (const rule of [...enabled].sort()) {
		const kind = kindOf(rule);
		if (kind === "native") continue;
		const mode = forced === "all" ? "all" : (explicitModes.get(rule) ?? (kind === "jev" ? "changed" : "all"));
		modes[rule] = mode;
		const plugin = pluginOf(rule);
		if (kind === "js" && mode === "changed" && plugin !== undefined) wrapped.add(plugin);
	}

	const root = options.root ?? callerDirectory() ?? process.cwd();
	const jsPlugins = config.jsPlugins?.map((entry) =>
		typeof entry !== "string" && wrapped.has(entry.name)
			? { name: entry.name, specifier: writeWrapper(root, entry.name, entry.specifier) }
			: entry,
	);

	const { rules: _rules, overrides: _overrides, jsPlugins: _jsPlugins, settings, ...rest } = config;
	return {
		...rest,
		...(jsPlugins === undefined ? {} : { jsPlugins }),
		...(rules === undefined ? {} : { rules }),
		...(overrides === undefined ? {} : { overrides }),
		settings: {
			...settings,
			changedLines: base === undefined ? { rules: modes } : { rules: modes, base },
		},
	};
}
